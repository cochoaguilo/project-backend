-- Schema matching the TypeORM entities (default naming: snake_case tables,
-- camelCase columns, which must be quoted in Postgres).
-- Keep DB_SYNCHRONIZE=false: the foreign keys below are not declared in the
-- entities, so TypeORM synchronize would drop them.

create table if not exists public.usuarios (
  id        integer generated by default as identity primary key,
  name      varchar not null,
  mail      varchar not null unique,
  password  varchar not null
);

create table if not exists public.ahorros (
  id          integer generated by default as identity primary key,
  name        varchar not null,
  quantity    integer not null,
  description varchar,
  type        varchar not null,
  date        date,
  "userId"    integer not null references public.usuarios(id) on delete cascade
);

create table if not exists public.cripto (
  id             integer generated by default as identity primary key,
  name           varchar not null,
  hold           double precision not null,
  platform       varchar not null,
  symbol         varchar not null,
  "purchaseDate" timestamp not null,
  "userId"       integer not null references public.usuarios(id) on delete cascade
);

create table if not exists public.deudas (
  id          integer generated by default as identity primary key,
  name        varchar not null,
  amount      double precision not null,
  description varchar not null,
  "userId"    integer not null references public.usuarios(id) on delete cascade
);

create table if not exists public.inversiones (
  id             integer generated by default as identity primary key,
  name           varchar not null,
  hold           double precision not null,
  platform       varchar not null,
  symbol         varchar not null,
  "purchaseDate" timestamp not null,
  "userId"       integer not null references public.usuarios(id) on delete cascade
);

-- Postgres does not index foreign key columns automatically.
create index if not exists ahorros_userid_idx     on public.ahorros("userId");
create index if not exists cripto_userid_idx      on public.cripto("userId");
create index if not exists deudas_userid_idx      on public.deudas("userId");
create index if not exists inversiones_userid_idx on public.inversiones("userId");

-- Block the public Data API. The backend connects as `postgres`, which
-- bypasses RLS, so it is unaffected.
alter table public.usuarios    enable row level security;
alter table public.ahorros     enable row level security;
alter table public.cripto      enable row level security;
alter table public.deudas      enable row level security;
alter table public.inversiones enable row level security;
